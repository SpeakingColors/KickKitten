#!/usr/bin/env python3
"""Generates src/engine/SpecTable.inc from assets/spec.json (exported from the mockup)."""
import json,os
d=json.load(open('assets/spec.json'))
def q(s):return '"'+s.replace('\\','\\\\').replace('"','\\"')+'"'
with open('src/engine/SpecEnum.inc','w') as f:
    f.write('// generated by tools/gen_spec.py, do not edit\n'+',\n'.join(x['id'] for x in d)+',\nNPARAMS\n')
with open('src/engine/SpecTable.inc','w') as f:
    f.write('// generated by tools/gen_spec.py, do not edit\n')
    for x in d:
        f.write('{%s,%s,%r,%r,%s,%d,%r,%s,%s},\n'%(q(x['id']),q(x['label']),float(x['min']),float(x['max']),q(x['unit']),x['dec'],float(x['def']),'true' if x['log'] else 'false',q(x['tip'])))
print(len(d),'params')
