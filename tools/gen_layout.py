#!/usr/bin/env python3
"""Generates src/ui/LayoutTable.inc from assets/layout.json (exported from the approved mockup)."""
import json
d=json.load(open('assets/layout.json'))
def q(s): return '"'+s.replace('\\','\\\\').replace('"','\\"').replace('\n',' ')+'"'
with open('src/ui/LayoutTable.inc','w') as f:
    f.write('// generated by tools/gen_layout.py, do not edit\n')
    f.write('static constexpr int kW = %d, kH = %d;\n'%(d['W'],d['H']))
    f.write('static const LItem kItems[] = {\n')
    for i in d['items']:
        r=[int(round(x)) for x in i['r']]
        f.write('{%s,%s,%s,%s,%s,%s,%d,%d,%d,%d},\n'%(q(i['tag']),q(i['cls']),q(i['id']),q(i['kid']),q(i['text']),q(i['tip']),*r))
    f.write('};\n')
    f.write('static const char* kCss[][2] = {\n'+''.join('{%s,%s},\n'%(q(k),q(v)) for k,v in d['css'].items())+'};\n')
print(len(d['items']))
