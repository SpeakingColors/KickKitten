#!/usr/bin/env python3
"""Generates src/engine/FactoryData.inc (factory presets, sound names) from assets/*.json (exported from the mockup)."""
import json
def q(s): return '"'+s.replace('\\','\\\\').replace('"','\\"')+'"'
pre=json.load(open('assets/presets.json')); bank=json.load(open('assets/bank.json'))
with open('src/engine/FactoryData.inc','w') as f:
    f.write('// generated by tools/gen_data.py, do not edit\n#define KK_FACTORY \\\n')
    for p in pre:
        kv=[]
        for k,v in p['p'].items():
            if k=='env': continue
            kv.append('%s=%s'%(k,repr(float(v))))
        env=';'.join('%s,%s,%s'%(repr(float(a[0])),repr(float(a[1])),repr(float(a[2]))) for a in p['p'].get('env') or [])
        f.write('  { %s, %s, %s, %s }, \\\n'%(q(p['name']),q(p.get('tag','')),q(';'.join(kv)),q(env)))
    f.write('\n#define KK_BANK \\\n')
    for b in bank['bank']:
        f.write('  { %s, %s, %s, %d }, \\\n'%(q(b['name']),q(b['group']),q(b['sub']),b['len']))
    f.write('\n')
print(len(pre),'presets',len(bank['bank']),'bank')
